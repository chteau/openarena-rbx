#!/usr/bin/env python3
"""Generate src/shared/bg/bg_itemlist.luau from the bg_itemlist[] initializer
in vendor/gamecode/code/game/bg_misc.c.

Each gitem_t becomes a table with the C field names; world_model is a 0-based
array of 4 (nil for NULL). Every item also carries `index` (ITEM_INDEX(it)),
since Luau has no pointer arithmetic. Enum tags are resolved to numbers with
the same tables tools/gen_consts.py builds.
"""
import re
import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).resolve().parent))
import gen_consts  # noqa: E402

ROOT = gen_consts.ROOT
SRC = gen_consts.GC / "game/bg_misc.c"
OUT = ROOT / "src/shared/bg/bg_itemlist.luau"
FIELDS = ["classname", "pickup_sound", "world_model", "icon", "pickup_name",
          "quantity", "giType", "giTag", "precaches", "sounds"]


def tokens(text):
    for m in re.finditer(r'"(?:[^"\\]|\\.)*"|[{},]|[A-Za-z_]\w*|-?\d+', text):
        yield m.group(0)


def main():
    known = {}
    for paths in gen_consts.TARGETS.values():
        gen_consts.parse(paths, known)
    text = gen_consts.strip_comments(SRC.read_text(errors="replace"))
    body = re.search(r"gitem_t\s+bg_itemlist\[\]\s*=\s*\{([\s\S]*?)\n\};", text).group(1)
    toks = list(tokens(body))
    items, i = [], 0

    def value(t):
        if t == "NULL":
            return None
        if t.startswith('"'):
            return t
        if re.fullmatch(r"-?\d+", t):
            return int(t)
        return (t, known[t])

    while i < len(toks):
        if toks[i] == ",":
            i += 1
            continue
        assert toks[i] == "{", toks[i]
        i += 1
        vals = []
        while toks[i] != "}":
            if toks[i] == ",":
                i += 1
                continue
            if toks[i] == "{":
                i += 1
                arr = []
                while toks[i] != "}":
                    if toks[i] != ",":
                        arr.append(value(toks[i]))
                    i += 1
                i += 1
                vals.append(arr)
                continue
            # adjacent string literals concatenate
            v = value(toks[i])
            i += 1
            while isinstance(v, str) and i < len(toks) and toks[i].startswith('"'):
                v = v[:-1] + toks[i][1:]
                i += 1
            vals.append(v)
        i += 1
        if len(vals) < len(FIELDS):  # trailing {NULL} terminator
            vals = [None, None, [], None, None, 0, 0, 0, None, None]
        assert len(vals) == len(FIELDS), vals
        items.append(vals)

    def lua(v):
        if v is None:
            return "nil"
        if isinstance(v, tuple):
            return f"{v[1]} --[[{v[0]}]]"
        return str(v)

    out = [
        "-- Generated by tools/gen_items.py from the bg_itemlist[] table in gamecode/code/game/bg_misc.c.",
        "-- Do not edit by hand. GPL-2.0 like the source it is derived from",
        "-- (Copyright (C) 1999-2005 Id Software, Inc., and the OpenArena team).",
        "-- bg_itemlist is 0-based like the C array; the last entry (all NULL) ends the list.",
        "",
        "local bg_itemlist = {}",
    ]
    for n, vals in enumerate(items):
        parts = [f"index = {n}"]
        for name, v in zip(FIELDS, vals):
            if name == "world_model":
                v = v + [None] * (4 - len(v))
                parts.append("world_model = { [0] = " + ", ".join(lua(x) for x in v) + " }")
            else:
                parts.append(f"{name} = {lua(v)}")
        out.append(f"bg_itemlist[{n}] = {{ " + ", ".join(parts) + " }")
    out.append("")
    out.append(f"return {{ bg_itemlist = bg_itemlist, bg_numItems = {len(items) - 1} }}\n")
    OUT.write_text("\n".join(out))
    print(f"{OUT.relative_to(ROOT)}: {len(items)} entries")


if __name__ == "__main__":
    main()
