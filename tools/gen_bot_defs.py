#!/usr/bin/env python3
"""Generate the bot side's Luau constant and struct tables from the C headers.

  src/server/bot/botlib/consts.luau   every #define/enum botlib sees (ioquake3
                                      q_shared.h, surfaceflags.h, botlib/*.h)
  src/server/bot/botlib/structs.luau  every botlib struct (headers and .c files)
  src/server/bot/ai_consts.luau       the bot AI's own headers (OpenArena 0.8.8
                                      ai_*.h, chars.h, inv.h, match.h, syn.h)
                                      plus botlib's public headers, minus what
                                      the game module's g_defs already has
  src/server/bot/ai_structs.luau      bot_state_t & co. and botlib's public
                                      structs, layered over g_structs

Reuses tools/gen_consts.py and tools/gen_structs.py.

Usage: tools/gen_bot_defs.py
"""
import re
import sys
from pathlib import Path

HERE = Path(__file__).resolve().parent
sys.path.insert(0, str(HERE))
import gen_consts  # noqa: E402
import gen_structs  # noqa: E402

ROOT = HERE.parent
IOQ = ROOT / "vendor/ioq3/code"
BL = IOQ / "botlib"
GAME = ROOT / "vendor/gamecode-088/code/game"

BOTLIB_HEADERS = [IOQ / "qcommon/q_shared.h", IOQ / "qcommon/surfaceflags.h"] + sorted(BL.glob("*.h"))
BOTLIB_C = sorted(BL.glob("*.c"))
PUBLIC = [BL / h for h in ("botlib.h", "be_aas.h", "be_ai_char.h", "be_ai_chat.h", "be_ai_gen.h",
                            "be_ai_goal.h", "be_ai_move.h", "be_ai_weap.h", "be_ea.h")]
AI_HEADERS = PUBLIC + [GAME / h for h in ("ai_main.h", "ai_dmq3.h", "ai_dmnet.h", "ai_team.h", "ai_chat.h",
                                         "ai_cmd.h", "ai_vcmd.h", "chars.h", "inv.h", "match.h", "syn.h")]
GAME_CONST_HEADERS = [p for paths in gen_consts.TARGETS.values() for p in paths]

# char-literal macros the evaluator cannot read
gen_consts.OVERRIDES["AASID"] = (ord("S") << 24) + (ord("A") << 16) + (ord("A") << 8) + ord("E")

HEADER = """-- Generated by tools/gen_bot_defs.py from {srcs}.
-- Do not edit by hand. GPL-2.0 like the headers it is derived from
-- (Copyright (C) 1999-2005 Id Software, Inc., and the OpenArena team).
"""

# C type spellings gen_structs does not know, folded to one it does
TYPE_FOLD = [
    (r"\bunsigned\s+short\s+int\b", "short"), (r"\bunsigned\s+short\b", "short"),
    (r"\bshort\s+int\b", "short"), (r"\bunsigned\s+char\b", "byte"), (r"\bunsigned\s+long\b", "long"),
    (r"\bunsigned\s+int\b", "int"), (r"\blong\s+int\b", "int"), (r"\bsigned\s+char\b", "char"), (r"\bsigned\s+int\b", "int"),
    (r"\bunion\s+cvalue\b", "cvalue_t"), (r"\bstruct\s+", ""),
]
# typedef'd scalars and aliases (aasfile.h, l_precomp.h ...)
EXTRA_SCALARS = {"aas_edgeindex_t", "aas_faceindex_t", "aas_portalindex_t", "cvalue_t", "bsp_link_t",
                 "sfxHandle_t", "fileHandle_t", "size_t", "qhandle_t"}
EXTRA_VECS = {"aas_vertex_t": "vec3_t"}


def fold(text):
    for a, b in TYPE_FOLD:
        text = re.sub(a, b, text)
    for a, b in EXTRA_VECS.items():
        text = re.sub(rf"\b{a}\b", b, text)
    return text


def consts(paths, known, skip=()):
    items = gen_consts.parse(paths, known)
    srcs = ", ".join(str(p.relative_to(ROOT / "vendor")) for p in paths)
    lines = [HEADER.format(srcs=srcs), "return {"]
    seen = set(skip)
    n = 0
    for name, v in items:
        if name in seen:
            continue
        seen.add(name)
        n += 1
        lines.append(f"\t{name} = {gen_consts.fmt(v)},")
    lines.append("}\n")
    return "\n".join(lines), n


def collect(paths):
    structs, enums = {}, set()
    for p in paths:
        text = fold(gen_consts.strip_comments(p.read_text(errors="replace")))
        text = re.sub(r"^\s*#.*$", "", text, flags=re.M)
        for m in re.finditer(r"typedef\s+enum\s*\w*\s*\{[\s\S]*?\}\s*(\w+)\s*;", text):
            enums.add(m.group(1))
        for m in re.finditer(r"typedef\s+(?!enum\b|union\b)(\w*)\s*\{([^{}]*)\}\s*(\w+)\s*;", text):
            structs[m.group(3)] = m.group(2)
            if m.group(1):
                gen_structs.ALIASES[m.group(1)] = m.group(3)
                gen_structs.ALIASES[m.group(1).rstrip("s").rstrip("_") + "_t"] = m.group(3)
    return structs, enums


LUAU_KEYWORDS = {"and", "break", "do", "else", "elseif", "end", "false", "for", "function", "if", "in",
                 "local", "nil", "not", "or", "repeat", "return", "then", "true", "until", "while"}


def structs(paths, base, known, extern=()):
    """extern: struct definitions the base module already provides (types only)."""
    ev = gen_consts.Evaluator(known)
    found, enums = collect(paths)
    types = dict(collect(extern)[0]) if extern else {}
    types.update(found)
    gen_structs.SCALARS.update(EXTRA_SCALARS)
    srcs = ", ".join(str(p.relative_to(ROOT / "vendor")) for p in paths)
    lines = [
        "-- Generated by tools/gen_bot_defs.py from the struct definitions in " + srcs + ".",
        "-- Do not edit by hand. GPL-2.0 like the headers it is derived from",
        "-- (Copyright (C) 1999-2005 Id Software, Inc., and the OpenArena team).",
        "-- S.<type>() returns a zeroed struct (numbers 0, qboolean false, vec3_t {[0]=0,0,0},",
        "-- char[] \"\", pointers nil, arrays 0-based); S.copy_<type>(dst, src) is C assignment.",
        "",
    ]
    if base:
        lines.append(f'local S = setmetatable({{}}, {{ __index = require("{base}") }})')
    else:
        lines.append("local S = {}")
    lines += [
        "",
        "local function vec3() return { [0] = 0, 0, 0 } end",
        "local function vecN(n) local t = { [0] = 0 } for i = 1, n - 1 do t[i] = 0 end return t end",
        "local function arr(n, f) local t = { [0] = f() } for i = 1, n - 1 do t[i] = f() end return t end",
        "local function deepcopy(d, s)",
        "\tfor k, v in s do",
        "\t\tif type(v) == \"table\" and type(d[k]) == \"table\" then deepcopy(d[k], v) else d[k] = v end",
        "\tend",
        "end",
        "S.deepcopy = deepcopy",
        "local function ptrcopy(d, s, depth)",
        "\tif depth > 1 then for k, v in s do ptrcopy(d[k], v, depth - 1) end return end",
        "\ttable.clear(d)",
        "\tfor k, v in s do d[k] = v end",
        "end",
        "S.arr = arr",
        "S.vec3 = vec3",
        "",
    ]
    names = [n for n in found if not n.startswith("q") or n not in ("qboolean",)]
    done = 0
    for name in names:
        body = found[name]
        try:
            # a field named after a Luau keyword (aas_reachability_t.end) gets a trailing _
            fl = [(f + "_" if f in LUAU_KEYWORDS else f, c, d) for f, c, d in gen_structs.fields(body, ev)]
            vals = [(f, c, d, gen_structs.default(c, d, types, enums)) for f, c, d in fl]
        except SystemExit as e:
            print(f"  skip {name}: {e}", file=sys.stderr)
            continue
        done += 1
        lines.append(f"function S.{name}()")
        lines.append("\treturn {")
        for f, c, d, v in vals:
            if v is not None:
                lines.append(f"\t\t{f} = {v},")
        lines.append("\t}")
        lines.append("end")
        lines.append(f"function S.copy_{name}(d, s)")
        for f, c, d, v in vals:
            lines.append("\t" + gen_structs.copy_stmt(f, c, d, types, enums))
        lines.append("\treturn d")
        lines.append("end")
        lines.append("")
    lines.append("return S\n")
    return "\n".join(lines), done


def write(rel, text, what):
    dst = ROOT / rel
    dst.parent.mkdir(parents=True, exist_ok=True)
    dst.write_text(text)
    print(f"{rel}: {what}")


def main():
    known = {}
    text, n = consts(BOTLIB_HEADERS, known)
    write("src/server/bot/botlib/consts.luau", text, f"{n} constants")
    cknown = dict(known)
    gen_consts.parse(BOTLIB_C, cknown)
    text, n = structs(BOTLIB_HEADERS + BOTLIB_C, None, cknown)
    write("src/server/bot/botlib/structs.luau", text, f"{n} structs")

    game_known = {}
    for paths in gen_consts.TARGETS.values():
        gen_consts.parse([ROOT / p.relative_to(gen_consts.ROOT) for p in paths], game_known)
    game_names = set(game_known)
    text, n = consts(AI_HEADERS, game_known, skip=game_names)
    write("src/server/bot/ai_consts.luau", text, f"{n} constants")
    extern = [ROOT / p.relative_to(gen_consts.ROOT) for _, paths, _, _ in gen_structs.TARGETS for p in paths]
    text, n = structs(AI_HEADERS, "../g_structs", game_known, extern)
    write("src/server/bot/ai_structs.luau", text, f"{n} structs")


if __name__ == "__main__":
    main()
