#!/usr/bin/env python3
"""Generate src/server/bot/g_botlib.luau: the game module's botlib traps.

In C the game calls trap_X (g_syscalls.c) -> syscall(BOTLIB_X, args) ->
the engine's SV_GameSystemCalls switch (sv_game.c) -> botlib_export->...
or an engine function. Both ends of that chain take the same arguments,
so with the port's out-parameter rule (outs dropped and returned) each
trap is a pass-through to the export function the switch names.

Usage: tools/gen_g_botlib.py
"""
import re
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
SYSCALLS = ROOT / "vendor/gamecode/code/game/g_syscalls.c"
SVGAME = ROOT / "vendor/ioq3/code/server/sv_game.c"

ENGINE = {  # cases the engine answers itself (sv_bot.c / sv_game.c)
    "BOTLIB_SETUP": "SVB.SV_BotLibSetup()",
    "BOTLIB_SHUTDOWN": "SVB.SV_BotLibShutdown()",
    "BOTLIB_GET_SNAPSHOT_ENTITY": "SVB.SV_BotGetSnapshotEntity(...)",
    "BOTLIB_GET_CONSOLE_MESSAGE": "SVB.SV_BotGetConsoleMessage(...)",
    "BOTLIB_USER_COMMAND": "SVB.SV_BotUserCommand(...)",
}


def main():
    sw = SVGAME.read_text(errors="replace")
    target = {}
    for m in re.finditer(r"case (BOTLIB_\w+):\s*(?:return\s+)?(?:FloatAsInt\(\s*)?botlib_export->([\w.]+)\(", sw):
        target[m.group(1)] = m.group(2)
    lines = []
    sc = SYSCALLS.read_text(errors="replace")
    for m in re.finditer(r"^[\w \t\*]*?\b(trap_\w+)\s*\(([^)]*)\)\s*\{\s*(?:return\s+|floatint_t\s+fi;\s*fi\.i\s*=\s*|(?:\(\w+\)\s*))*syscall\(\s*(BOTLIB_\w+)", sc, re.M):
        name, args, case = m.group(1), m.group(2), m.group(3)
        if case in ENGINE:
            body = ENGINE[case]
        elif case in target:
            body = f"SVB.botlib_export.{target[case]}(...)"
        else:
            raise SystemExit(f"no engine mapping for {name} ({case})")
        lines.append(f"-- {' '.join(m.group(0).split('{')[0].split())}\nfunction G.{name}(...)\n\treturn {body}\nend")
    head = (ROOT / "src/server/bot/botlib/b_local.luau").read_text().split("]]")[0] + "]]\n"
    head = head.replace("(botlib)", "(game/g_syscalls.c, the botlib traps)")
    out = head + """--!native
-- Generated by tools/gen_g_botlib.py. The game module's botlib traps: each
-- one goes where ioquake3's SV_GameSystemCalls sends its syscall, the
-- botlib export (sv_bot.luau's botlib_export) or the engine's bot code.
-- Arguments pass straight through; out-parameters come back as extra
-- return values on both sides (docs/bots-notes.md, "Out-parameters").

local G = require("../g_local")
local SVB = require("./sv_bot")

""" + "\n\n".join(lines) + "\n\nreturn nil\n"
    (ROOT / "src/server/bot/g_botlib.luau").write_text(out)
    print(f"g_botlib.luau: {len(lines)} traps")


if __name__ == "__main__":
    main()
