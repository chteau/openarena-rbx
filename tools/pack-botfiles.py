#!/usr/bin/env python3
"""Pack OpenArena's botfiles/ (bot characters, chats, item and weapon
weights, synonyms, match templates) into one Luau buffer blob, in the
converter's format (docs/formats/luau-blobs.md): chunk modules
build/botfiles/luau/Botfiles_NNN.luau and the index Botfiles.luau.

Blob layout (little-endian): "OABF", u32 count, then per file
u16 path length, path (UTF-8, e.g. "botfiles/bots/sarge_c.c"),
u32 data length, data. Later pk3s override earlier ones, like the
search path. Bots.MountBotfiles reads it back.

Usage: tools/pack-botfiles.py
"""
import base64
import hashlib
import struct
import zipfile
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
PK3 = ROOT / "vendor/oa088/openarena-0.8.8/baseoa"
PAKS = ["pak6-misc.pk3", "pak6-patch085.pk3", "pak6-patch088.pk3"]
OUT = ROOT / "build/botfiles"
CHUNK = 190000 // 4 * 4  # base64 characters per chunk module, a multiple of 4

DECODER = '''--!native
-- Generated by tools/pack-botfiles.py. One chunk of a binary blob; see the index module.
local function decode(s: string): buffer
	local map = {}
	local alphabet = "ABCDEFGHIJKLMNOPQRSTUVWXYZabcdefghijklmnopqrstuvwxyz0123456789+/"
	for i = 1, 64 do
		map[string.byte(alphabet, i)] = i - 1
	end
	local n = #s
	local pad = 0
	if n > 0 and string.byte(s, n) == 61 then pad += 1 end
	if n > 1 and string.byte(s, n - 1) == 61 then pad += 1 end
	local len = n // 4 * 3 - pad
	local out = buffer.create(len)
	local o = 0
	for i = 1, n, 4 do
		local a, b, c, d = string.byte(s, i, i + 3)
		local v = map[a] * 262144 + map[b] * 4096 + (map[c] or 0) * 64 + (map[d] or 0)
		buffer.writeu8(out, o, v // 65536)
		if o + 1 < len then buffer.writeu8(out, o + 1, (v // 256) % 256) end
		if o + 2 < len then buffer.writeu8(out, o + 2, v % 256) end
		o += 3
	end
	return out
end
'''


def main():
    files = {}
    for pak in PAKS:
        with zipfile.ZipFile(PK3 / pak) as z:
            for info in z.infolist():
                if info.filename.lower().startswith("botfiles/") and not info.is_dir():
                    files[info.filename] = z.read(info)
    blob = bytearray(b"OABF" + struct.pack("<I", len(files)))
    for path in sorted(files):
        p = path.encode()
        blob += struct.pack("<H", len(p)) + p + struct.pack("<I", len(files[path])) + files[path]
    (OUT / "luau").mkdir(parents=True, exist_ok=True)
    (OUT / "botfiles.bin").write_bytes(blob)
    text = base64.b64encode(bytes(blob)).decode()
    chunks = []
    for i in range(0, len(text), CHUNK):
        name = f"Botfiles_{len(chunks):03d}"
        (OUT / "luau" / f"{name}.luau").write_text(DECODER + f'return decode("{text[i:i + CHUNK]}")\n')
        chunks.append(name)
    sha = hashlib.sha256(blob).hexdigest()
    names = ", ".join(f'"{c}"' for c in chunks)
    (OUT / "luau" / "Botfiles.luau").write_text(
        "-- Generated by tools/pack-botfiles.py. Require each chunk (sibling ModuleScripts) in order and\n"
        f"-- join them: the result is {len(blob)} bytes, sha256 {sha}.\n"
        f'return {{ name = "Botfiles", size = {len(blob)}, sha256 = "{sha}", chunks = {{ {names} }} }}\n')
    print(f"build/botfiles: {len(files)} files, {len(blob)} bytes, {len(chunks)} chunk(s)")


if __name__ == "__main__":
    main()
