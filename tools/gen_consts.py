#!/usr/bin/env python3
"""Generate Luau constant tables from the OpenArena / ioquake3 C headers.

Every numeric `#define` and every `typedef enum` in the listed headers becomes
a field of the generated module, so the Luau port keeps the C names verbatim.
Macros with a float suffix (`0.7f`) are emitted as their float32 value, the
value the C code actually compares against.

Usage: tools/gen_consts.py   (writes src/shared/consts.luau, src/server/g_consts.luau)
"""
import re
import struct
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
GC = ROOT / "vendor/gamecode/code"

TARGETS = {
    "src/shared/consts.luau": [
        GC / "qcommon/q_shared.h",
        GC / "qcommon/surfaceflags.h",
        GC / "game/bg_public.h",
        GC / "game/bg_local.h",
    ],
    "src/server/g_consts.luau": [
        GC / "game/g_local.h",
        GC / "game/g_team.h",
        GC / "game/g_public.h",
    ],
}

HEADER = """-- Generated by tools/gen_consts.py from {srcs}.
-- Do not edit by hand. GPL-2.0 like the headers it is derived from
-- (Copyright (C) 1999-2005 Id Software, Inc., and the OpenArena team).
--!strict
"""


# <math.h> is included before q_shared.h, so its double M_PI wins over the
# `#ifndef M_PI ... 3.14159265358979323846f` fallback in native builds.
OVERRIDES = {"M_PI": 3.141592653589793}


def f32(x):
    return struct.unpack("f", struct.pack("f", x))[0]


def strip_comments(text):
    text = re.sub(r"/\*.*?\*/", " ", text, flags=re.S)
    return re.sub(r"//[^\n]*", "", text)


class Evaluator:
    def __init__(self, known):
        self.known = known

    def __call__(self, expr):
        e = expr.strip()
        if not e or '"' in e or "'" in e:
            return None
        isfloat = bool(re.search(r"\d\.\d*f\b|\d+f\b", e))
        e = re.sub(r"(\d+\.\d*|\d+)[fF]\b", r"\1", e)
        e = re.sub(r"(0x[0-9a-fA-F]+|\d+)[uUlL]+\b", r"\1", e)
        e = re.sub(r"\((?:int|unsigned|float|unsigned int)\)", "", e)

        def sub(m):
            name = m.group(0)
            if name in self.known:
                return repr(self.known[name])
            raise KeyError(name)

        try:
            e = re.sub(r"\b[A-Za-z_]\w*\b", sub, e)
        except KeyError:
            return None
        e = e.replace("&&", " and ").replace("||", " or ")
        if re.search(r"[^0-9a-fA-FxX.+\-*/%()<>|&^~ eE]", e.replace(" and ", "").replace(" or ", "")):
            return None
        try:
            v = eval(e, {"__builtins__": {}})
        except Exception:
            return None
        if isinstance(v, bool) or not isinstance(v, (int, float)):
            return None
        if isfloat:
            v = f32(float(v))
        if isinstance(v, int) and v >= 2**31 and v < 2**32:
            v -= 2**32  # C int bit patterns such as 0x80000000
        return v


def parse(paths, known):
    out = []
    ev = Evaluator(known)
    for p in paths:
        text = strip_comments(p.read_text(errors="replace"))
        text = text.replace("\\\n", " ")
        pos = 0
        token = re.compile(r"^[ \t]*#[ \t]*define[ \t]+(\w+)(\([^)]*\))?[ \t]*([^\n]*)$|typedef\s+enum\s*\w*\s*\{([\s\S]*?)\}\s*(\w+)\s*;", re.M)
        for m in token.finditer(text):
            if m.group(1):
                name, args, body = m.group(1), m.group(2), m.group(3)
                if args or name in known:
                    continue
                v = OVERRIDES.get(name, ev(body))
                if v is not None:
                    known[name] = v
                    out.append((name, v))
            else:
                body = m.group(4)
                cur = -1
                for item in body.split(","):
                    item = item.strip()
                    if not item:
                        continue
                    if "=" in item:
                        n, e = item.split("=", 1)
                        n = n.strip()
                        v = ev(e)
                        if v is None:
                            continue
                        cur = v
                    else:
                        n = item
                        cur += 1
                    if re.fullmatch(r"\w+", n):
                        known[n] = cur
                        out.append((n, cur))
    return out


def fmt(v):
    if isinstance(v, float):
        if v == int(v) and abs(v) < 2**53:
            return str(int(v))
        return repr(v)
    return str(v)


def main():
    known = {}
    for target, paths in TARGETS.items():
        items = parse(paths, known)
        srcs = ", ".join(str(p.relative_to(ROOT / "vendor")) for p in paths)
        lines = [HEADER.format(srcs=srcs), "return {"]
        seen = set()
        for n, v in items:
            if n in seen:
                continue
            seen.add(n)
            lines.append(f"\t{n} = {fmt(v)},")
        lines.append("}\n")
        dst = ROOT / target
        dst.parent.mkdir(parents=True, exist_ok=True)
        dst.write_text("\n".join(lines))
        print(f"{target}: {len(seen)} constants")


if __name__ == "__main__":
    sys.exit(main())
