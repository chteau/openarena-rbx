#!/usr/bin/env python3
"""Builds place/openarena.rbxl through rbx-native's MCP server.

  place/assemble.py [--launch] [--maps all|oa_dm1,oa_ctf2] [--players sarge,sergei]
                    [--startup "map oa_dm1; addbot sarge 2"] [--place place/openarena.rbxl]

Every instance is made by MCP tool calls against a running rbxstudio editor
(`rbxstudio --mcp`, stdio JSON-RPC): `multi_edit` creates the scripts from
src/, src/first/ and place/boot/, `execute_luau` (Edit) makes folders, remotes, the
lighting and the generated data modules, `insert_asset` brings in the
uploaded map Models, and `inspect_instance` / `search_game_tree` check the
result. Nothing is written into the .rbxl by hand: the editor saves it
(MCP `save_place`).

Inputs:
  build/                  `oaconv convert` output (maps, md3, SoundIndex, manifest)
  build/botfiles/         tools/pack-botfiles.py
  place/asset-ids.json    place/resolve_ids.py (upload lock -> image/mesh ids)
  vendor/oa088/...        the pk3s, for the client's text-file pack

--launch starts the editor on --place (an empty place is made with lune
first if the file is missing) with XDG_* pointed at --home, and closes it
when done. Without it, the editor with the MCP beta on must already have
--place open. RBXSTUDIO names the binary.

Images, sounds and map meshes without an id in place/asset-ids.json (still
uploading, or held back for review in tools/oaconv/upload-hold.txt) are left
out: the client draws OA's default (white) image for them. Re-run
resolve_ids.py and this script once they have ids.
"""
