def lua_value(v):
    if isinstance(v, bool):
        return 'true' if v else 'false'
    if isinstance(v, (int, float)):
        return repr(v)
    if isinstance(v, str):
        return lua_str(v)
    if isinstance(v, list):
        return '{' + ', '.join(lua_value(x) for x in v) + '}'
    if isinstance(v, dict):
        return '{' + ', '.join('[%s] = %s' % (lua_str(str(k)), lua_value(x)) for k, x in v.items()) + '}'
    if v is None:
        return 'nil'
    raise TypeError(type(v))


def is_lod(stem):
    return stem[-2:] in ('_1', '_2') and stem[-3:-2] != '_'


def asset_index(ids, manifest, models_json, map_names, players):
    """(init, parts, extra source, md3 modules [(key, [(name, source)])])."""
    # every image the converter lists for upload; one without an id yet (held
    # for review, or still uploading) is registered without one, so the
    # client draws OA's default white image instead of failing to register
    # it (a player model without its icon fails CG_RegisterClientModelname)
    images = []
    for u in manifest['uploads']:
        path = u['path']
        if u['type'] != 'Image' or not path.startswith('images/'):
            continue
        w, h = png_size(os.path.join(BUILD, path))
        key = path[len('images/'):-len('.png')].lower()
        if cda.roster.excludes(key + '.tga') or cda.roster.excludes(key + '.jpg'):
            continue
        e = ids['images'].get(path)
        idf = 'id = %s, ' % lua_str('rbxassetid://%d' % e['image']) if e else ''
        images.append('[%s] = { %sw = %d, h = %d }' % (lua_str(key), idf, w, h))
    parts = parts_of(sorted(images))

    extra = {'atlases': {}, 'music': {}, 'meshes': {}, 'maps': {}}
    for path, aid in ids['audio'].items():
        if path.startswith('sound/'):
            extra['atlases'][os.path.basename(path)] = 'rbxassetid://%d' % aid
        elif path.startswith('music/'):
            extra['music'][path[:-4].lower()] = 'rbxassetid://%d' % aid
    # static MD3 surfaces the converter bundled and uploaded: R3D draws them
    # as MeshParts instead of EditableMeshes
    for b in models_json.get('static_bundles', []):
        got = ids['models'].get(b['file'])
        if not got:
            continue
        centers = {m['name']: m['center'] for m in b['meshes']}
        for md3, info in models_json['md3'].items():
            if not info.get('static'):
                continue
            stem = md3[:-4]
            for s in info.get('surfaces', []):
                name = stem.replace('/', '_') + '_' + s['name']
                mesh = got['meshes'].get(name)
                if mesh and name in centers:
                    extra['meshes'][(stem + '#' + s['name']).lower()] = {'id': mesh['mesh'], 'c': centers[name]}
    for name in map_names:
        mp = manifest['maps'][name]
        meshes = [{'name': m['name'], 'shader': m['shader'], 'class': m['class'], 'overlay': m['overlay']}
                  for g in mp['glb'] for m in g['meshes']]
        sky = next((m['shader'] for m in meshes if m['class'] == 'sky'), None)
        extra['maps'][name] = {'meshes': meshes}
        if sky:
            extra['maps'][name]['sky'] = sky
    extra_src = '-- generated by place/assemble.py\nreturn ' + lua_value(extra) + '\n'

    md3 = []
    for path, info in sorted(models_json['md3'].items()):
        stem = path[:-4]
        if is_lod(stem):
            continue
        if stem.startswith('models/players/') and stem.split('/')[2] not in players:
            continue
        mod = os.path.join(BUILD, info['module'])
        d, base = os.path.dirname(mod), os.path.basename(mod)
        idx = open(mod + '.luau').read()
        mods = [(base, idx)]
        n = 0
        while os.path.exists(os.path.join(d, '%s_%03d.luau' % (base, n))):
            mods.append(('%s_%03d' % (base, n), open(os.path.join(d, '%s_%03d.luau' % (base, n))).read()))
            n += 1
        md3.append((stem.lower(), mods))
    init = ASSET_INDEX_INIT.replace('@N', str(len(parts)))
    sounds = open(os.path.join(BUILD, 'SoundIndex.luau')).read()
    return init, parts, extra_src, sounds, md3


def blob_dir(d):
    """The converter's buffer modules in d, as (name, source)."""
    return [(f[:-5], open(os.path.join(d, f)).read()) for f in sorted(os.listdir(d)) if f.endswith('.luau')]


# -------------------------------------------------------------------- pushing

PUSH_HEAD = '''
local function at(root, path, class)
	local node = root
	for i, name in path do
		local child = node:FindFirstChild(name)
		local last = i == #path
		if child == nil then
			child = Instance.new(if last then class else "Folder")
			child.Name = name
			child.Parent = node
		end
		node = child
	end
	return node
end
'''


class Pusher:
    """Batches `at(root, path, class).Source = ...` lines into execute_luau calls."""

    def __init__(self, mcp):
        self.mcp, self.batch, self.size, self.count = mcp, [], 0, 0

    def module(self, root, path, source, cls='ModuleScript'):
        line = 'at(%s, {%s}, %s).Source = %s' % (root, ', '.join(lua_str(p) for p in path), lua_str(cls),
                                                  long_string(source))
        if self.size + len(line) > BATCH:
            self.flush()
        self.batch.append(line)
        self.size += len(line)
        self.count += 1

    def flush(self):
        if self.batch:
            self.mcp.luau(PUSH_HEAD + '\n'.join(self.batch))
            self.batch, self.size = [], 0


RS = 'game:GetService("ReplicatedStorage")'
SSS = 'game:GetService("ServerScriptService")'
SS = 'game:GetService("ServerStorage")'


def src_modules():
    """(top dir, path below it, source) for every module in src/ (dev fixtures aside)."""
    out = []
    src = os.path.join(ROOT, 'src')
    for dirpath, _, files in os.walk(src):
        for f in sorted(files):
            rel = os.path.relpath(os.path.join(dirpath, f), src)
            if not f.endswith('.luau') or f.endswith(('.client.luau', '.server.luau')) or rel.startswith('client/dev'):
                continue
            out.append(rel[:-5].split(os.sep))
    return sorted(out)


def push_scripts(mcp, push):
    """Folders first (execute_luau), then every module through multi_edit.
    multi_edit resolves paths ignoring case and so refuses a script whose
    name differs only in case from a sibling (q/Consts next to the folder
    q/consts): those few go through execute_luau instead."""
    mods = src_modules()
    targets = []
    for p in mods:
        if p[0] in ('client', 'ui', 'shared'):
            targets.append(('ReplicatedStorage.OA', p))
        if p[0] in ('server', 'shared'):
            targets.append(('ServerScriptService.OA', p))
    folders = sorted({(t, tuple(p[:i])) for t, p in targets for i in range(1, len(p))})
    lines = []
    for t, f in folders:
        root = RS if t.startswith('Replicated') else SSS
        lines.append('at(at(%s, {"OA"}, "Folder"), {%s}, "Folder")' % (root, ', '.join(lua_str(x) for x in f)))
    mcp.luau(PUSH_HEAD + 'at(%s, {"OA"}, "Folder") at(%s, {"OA"}, "Folder")\n' % (RS, SSS) + '\n'.join(lines))
    for t, p in targets:
        source = open(os.path.join(ROOT, 'src', *p) + '.luau').read()
        try:
            multi_edit(mcp, t + '.' + '.'.join(p), source, 'ModuleScript')
        except RuntimeError as e:
            if 'differs only in case' not in str(e):
                raise
            push.module(RS if t.startswith('Replicated') else SSS, ['OA'] + p, source)
            push.flush()
            print('  execute_luau (case clash):', t + '.' + '.'.join(p))
    multi_edit(mcp, 'ServerScriptService.OA.Boot', open(os.path.join(ROOT, 'place/boot/Boot.server.luau')).read(), 'Script')
    multi_edit(mcp, 'StarterPlayer.StarterPlayerScripts.OAClient',
               open(os.path.join(ROOT, 'src/client/OAClient.client.luau')).read(), 'LocalScript')
    # the arriving teleport's loading screen runs before ReplicatedStorage replicates
    multi_edit(mcp, 'ReplicatedFirst.OALoadingScreen', open(os.path.join(ROOT, 'src/first/LoadingScreen.luau')).read(), 'ModuleScript')
    multi_edit(mcp, 'ReplicatedFirst.OAArrival', open(os.path.join(ROOT, 'src/first/Arrival.client.luau')).read(), 'LocalScript')
    return len(targets) + 4


def multi_edit(mcp, path, source, cls):
    mcp.tool('multi_edit', {'datamodel_type': 'Edit', 'file_path': path, 'className': cls,
                            'edits': [{'old_string': '', 'new_string': source}]})


