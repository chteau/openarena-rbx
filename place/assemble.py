def launch(place, home):
    if not os.path.exists(place):
        with tempfile.TemporaryDirectory() as tmp:
            script = os.path.join(tmp, 'empty.luau')
            open(script, 'w').write(EMPTY_PLACE)
            subprocess.run([os.environ.get('LUNE', os.path.expanduser('~/.local/bin/lune')), 'run', script, place],
                           check=True)
    env = dict(os.environ, XMODIFIERS='@im=none')
    # XDG_DATA_HOME stays: flatpak finds its user installs (Sober, for Play) there
    for k in ('CONFIG', 'CACHE', 'STATE'):
        env['XDG_%s_HOME' % k] = os.path.join(home, k.lower())
        os.makedirs(env['XDG_%s_HOME' % k], exist_ok=True)
    beta = os.path.join(home, 'config', 'rbx-native', 'beta.json')
    os.makedirs(os.path.dirname(beta), exist_ok=True)
    if not os.path.exists(beta):
        open(beta, 'w').write('{"enabled":["mcp-server"]}')
    os.environ.update({k: v for k, v in env.items() if k.startswith('XDG_')})
    proc = subprocess.Popen([os.environ.get('RBXSTUDIO', 'rbxstudio'), place], env=env,
                            stdout=subprocess.DEVNULL, stderr=subprocess.DEVNULL)
    for _ in range(60):
        time.sleep(1)
        try:
            return proc, MCP()
        except Exception:
            continue
    proc.terminate()
    raise RuntimeError('the editor did not come up')


