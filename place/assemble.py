def build_map(mcp, push, name, manifest, ids, with_meshes):
    mp = manifest['maps'][name]
    d = os.path.join(BUILD, mp['dir'], 'luau')
    lg = mp.get('lightgrid')
    attrs = {'Checksum': mp['checksum'], 'LightGrid': json.dumps(
        {'origin': lg['origin'], 'size': lg['size'], 'bounds': lg['bounds']}) if lg else None}
    mcp.luau(PUSH_HEAD + '''
local m = at(game:GetService("ServerStorage"), {"OAMaps", %s}, "Folder")
local old = m:FindFirstChild("Data")
if old then old:Destroy() end
m:SetAttribute("Checksum", %d)
m:SetAttribute("LightGrid", %s)
at(m, {"Data"}, "Folder")
at(m, {"Meshes"}, "Folder")
return "ok"''' % (lua_str(name), attrs['Checksum'], lua_value(attrs['LightGrid'])))
    for mod, source in blob_dir(d):
        push.module(SS, ['OAMaps', name, 'Data', mod], source)
    push.flush()
    if not with_meshes:
        return 'data only'
    # meshes: the uploaded Model per glb, inserted as-is, then placed
    info, inserted = {}, 0
    for g in mp['glb']:
        got = ids['models'].get('%s/%s' % (mp['dir'], g['file']))
        if not got:
            continue
        for m in g['meshes']:
            tex = ids['images'].get(m['texture'] or '')
            info[m['name']] = {'c': m['center'], 's': m['size'], 'k': m['class'],
                               't': 'rbxassetid://%d' % tex['image'] if tex else None}
        mcp.tool('insert_asset', {'assetId': str(got['asset']), 'assetType': 'Model',
                                  'parentPath': 'ServerStorage.OAMaps.%s.Meshes' % name})
        inserted += 1
    if not inserted:
        return 'no uploaded meshes'
    return mcp.luau(FIX_MESHES % (lua_str(name), lua_value(info)))


