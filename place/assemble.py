# ---------------------------------------------------------------- generation

def png_size(path):
    with open(path, 'rb') as f:
        head = f.read(24)
    return struct.unpack('>II', head[16:24])


def parts_of(entries):
    """Split table entries into part modules under LIMIT characters."""
    parts, cur, size = [], [], 0
    for e in entries:
        if size + len(e) > LIMIT and cur:
            parts.append(cur)
            cur, size = [], 0
        cur.append(e)
        size += len(e) + 2
    if cur:
        parts.append(cur)
    return ['-- generated by place/assemble.py\nreturn {\n' + ',\n'.join(p) + '\n}\n' for p in parts]


def files_pack():
    """The client's FS pack (docs/client-notes.md): every text file the game
    reads plus the list of every data path, from the pk3s in search order,
    with the player roster applied (tools/roster.py)."""
    shipped = cda.roster.Shipped(cda.BASEOA)
    owner, files = shipped.owner, shipped.text_files()
    entries = ['[%s] = %s' % (lua_str(k), lua_str(v)) for k, v in sorted(files.items())]
    entries += [lua_str(k) for k in sorted(owner) if k not in files]
    init = '-- generated by place/assemble.py: OA text files and the list of every data path\n' + \
        cda.MERGE['Files'].replace('@N', str(len(parts_of(entries))))
    return init, parts_of(entries)


