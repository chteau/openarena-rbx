def main():
    ap = argparse.ArgumentParser(description=__doc__.split('\n')[0])
    ap.add_argument('--place', default=os.path.join(ROOT, 'place', 'openarena.rbxl'))
    ap.add_argument('--maps', default='all')
    ap.add_argument('--players', help='player models to ship (default: every kept roster model with a body)')
    ap.add_argument('--startup', default='bot_enable 1; g_gametype 0; fraglimit 20; timelimit 10; map oa_dm1')
    ap.add_argument('--keep-maps', action='store_true', help='keep map folders already in the place')
    ap.add_argument('--no-meshes', action='store_true')
    ap.add_argument('--launch', action='store_true')
    ap.add_argument('--home', default=os.path.join(ROOT, '.studio-home'))
    args = ap.parse_args()
    place = os.path.abspath(args.place)

    manifest = json.load(open(os.path.join(BUILD, 'manifest.json')))
    models_json = json.load(open(os.path.join(BUILD, 'models.json')))
    ids = json.load(open(os.path.join(ROOT, 'place', 'asset-ids.json')))
    names = sorted(manifest['maps']) if args.maps == 'all' else args.maps.split(',')
    if args.players is None:
        # the roster's kept models with a converted body: the bots wear them
        players = {m for m in cda.roster.config()['kept'] if 'models/players/%s/lower.md3' % m in models_json['md3']}
    else:
        players = set(p for p in args.players.split(',') if p)
    dropped = sorted(p for p in players if cda.roster.model_excluded(p))
    if dropped:
        sys.exit('--players: %s not in the roster (tools/oaconv/roster.json)' % ','.join(dropped))

    proc = None
    if args.launch:
        proc, mcp = launch(place, args.home)
    else:
        mcp = MCP()
    t0 = time.time()
    try:
        print(mcp.tool('get_studio_state', {})[0]['text'].replace('\n', '; '))
        keep = names if args.keep_maps else []
        mcp.luau(CLEAR % lua_value(keep))
        push = Pusher(mcp)
        n = push_scripts(mcp, push)
        print(f'{n} scripts (multi_edit), {time.time() - t0:.0f}s')
        print(mcp.luau(SETUP % lua_str(args.startup)))

        init, parts = files_pack()
        push.module(RS, ['OA', 'client', 'sys', 'Files'], init)
        for i, p in enumerate(parts, 1):
            push.module(RS, ['OA', 'client', 'sys', 'Files', 'part_%d' % i], p)
        init, parts, extra, sounds, md3 = asset_index(ids, manifest, models_json, names, players)
        base = ['OA', 'client', 'sys', 'AssetIndex']
        push.module(RS, base, init)
        for i, p in enumerate(parts, 1):
            push.module(RS, base + ['part_%d' % i], p)
        push.module(RS, base + ['Extra'], extra)
        push.module(RS, base + ['Sounds'], sounds)
        for key, mods in md3:
            for name, source in mods:
                push.module(RS, base + ['Models', key, name], source)
        for name, source in blob_dir(os.path.join(BUILD, 'botfiles', 'luau')):
            push.module(SS, ['OABotfiles', name], source)
        push.flush()
        print(f'{push.count} data modules (execute_luau), {len(md3)} md3 models, {time.time() - t0:.0f}s')

        for name in names:
            r = build_map(mcp, push, name, manifest, ids, not args.no_meshes)
            print(f'  {name}: {r.strip()} ({time.time() - t0:.0f}s)')

        tree = mcp.tool('search_game_tree', {'datamodel_type': 'Edit', 'path': 'ServerStorage.OAMaps', 'max_depth': 1,
                                             'head_limit': 5})
        print(tree[0]['text'][:600])
        print(mcp.tool('inspect_instance', {'path': 'ServerScriptService.OA.Boot'})[0]['text'][:600])
        mcp.tool('save_place', {})
        size = os.path.getsize(place)
        print(f'saved {place}: {size / 1e6:.1f} MB, {time.time() - t0:.0f}s')
    finally:
        mcp.close()
        if proc:
            proc.terminate()
            proc.wait()


